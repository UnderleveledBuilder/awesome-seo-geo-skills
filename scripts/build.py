def tr(obj, key: str, lang: str):
    """取字段的当前语言版本：英文取 key_en，没有就退回中文。obj 是字符串时原样返回。"""
    if isinstance(obj, str):
        return obj
    return (obj.get(f"{key}_en") or obj.get(key)) if lang == "en" else obj.get(key)


def value_label(v, lang: str, short: bool = False) -> str:
    if isinstance(v, str):
        return v
    return (tr(v, "short", lang) if short else None) or tr(v, "label", lang)


def ordered(f: dict, lang: str) -> list[str]:
    """维度值的顺序：英文版可以用 order_en 另排（比如英文读者先看 X、YouTube）。"""
    order = f.get("order_en") if lang == "en" else None
    return list(order) + [k for k in f["values"] if k not in order] if order else list(f["values"])


def gh_url(repo: str) -> str:
    return f"https://github.com/{repo}"


def display_name(s: dict) -> str:
    return s.get("name") or s["repo"].split("/", 1)[1]


def fmt_stars(n: int | None) -> str:
    if n is None:
        return "—"
    return f"{n / 1000:.1f}k".replace(".0k", "k") if n >= 1000 else str(n)


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def stars(s: dict, meta: dict) -> int:
    return meta.get(s["repo"], {}).get("stars", -1)


def sort_key(s: dict, meta: dict):
    return (s.get("tier") != "featured", -stars(s, meta), display_name(s).lower())


def by_stars(items, meta: dict) -> list[dict]:
    return sorted(items, key=lambda s: -stars(s, meta))


def format_badge(taxonomy: dict, key: str, lang: str) -> str:
    f = taxonomy["formats"].get(key)
    if isinstance(f, dict) and f.get("badge"):
        return tr(f, "badge", lang)
    zh, en = DEFAULT_BADGES.get(key, ("", ""))
    return en if lang == "en" else zh


def status_mark(m: dict, ref: dt.date | None) -> str:
    if m.get("status") == "missing":
        return " ⚠️"
    if m.get("archived"):
        return " 📦"
    if ref and m.get("pushed_at") and (ref - dt.date.fromisoformat(m["pushed_at"])).days > STALE_DAYS:
        return " 💤"
    return ""


def entry(s: dict, m: dict, ref: dt.date | None, taxonomy: dict, ui: dict, lang: str) -> str:
    star = "🌟 " if s.get("tier") == "featured" else ""
    out = f"- {star}**[{display_name(s)}]({gh_url(s['repo'])})** · ★ {fmt_stars(m.get('stars'))}<br>{cell(tr(s, 'desc', lang))}"
    for field, f in facets(taxonomy).items():
        if s.get(field) and f.get("in_entry", True):
            shorts = " · ".join(value_label(f["values"][v], lang, short=True) for v in ordered(f, lang) if v in s[field])
            out += f"<br><sub>{tr(f, 'prefix', lang) or ''}{shorts}</sub>"
    sub = [ui["updated"].format(f"{m.get('pushed_at') or '—'}{status_mark(m, ref)}")]
    if badge := format_badge(taxonomy, s["format"], lang):
        sub.append(badge)
    sub.append(ui["lang"].get(s["lang"], s["lang"]))
    if m.get("skill_count", 0) > 1:
        sub.append(ui["skill_count"].format(f"{m['skill_count']}{'+' if m.get('skill_count_truncated') else ''}"))
    if m.get("license"):
        sub.append(m["license"])
    out += f"<br><sub>{' · '.join(sub)}</sub>"
    if s.get("note"):
        out += f"<br><sub>💡 {cell(tr(s, 'note', lang))}</sub>"
    return out


def install_cmd(s: dict) -> str | None:
    if s.get("install"):
        return s["install"]
    if s["format"] == "skill":
        return f"npx skills add {s['repo']}"
    return None


def render_group(key: str, group: dict, items: list[dict], meta: dict, ref: dt.date | None, taxonomy: dict,
                 ui: dict, lang: str) -> list[str]:
    out = [f'<a id="group-{key}"></a>', f"### {tr(group, 'label', lang)}", ""]
    if group.get("intro"):
        out += [tr(group, "intro", lang), ""]
    for s in items:
        out += [entry(s, meta.get(s["repo"], {}), ref, taxonomy, ui, lang), ""]
    cmds = [(display_name(s), install_cmd(s)) for s in items if install_cmd(s)]
    if cmds:
        out += ["", f"<details><summary>{ui['install']}</summary>", "", "```bash", ui["install_note"]]
        for name, cmd in cmds:
            out += [f"# {name}", cmd]
        out += ["```", "", "</details>"]
    return out + [""]


def new_entries(skills: list[dict], meta: dict, ref: dt.date | None) -> list[dict]:
    if ref is None:
        return []

    def age(s):
        seen = meta.get(s["repo"], {}).get("first_seen")
        return (ref - dt.date.fromisoformat(seen)).days if seen else None

    hits = [s for s in skills if (a := age(s)) is not None and 0 <= a < NEW_DAYS]
    return sorted(hits, key=lambda s: (age(s), -stars(s, meta)))


def render_new(items: list[dict], meta: dict, ui: dict, lang: str) -> list[str]:
    out = ['<a id="new"></a>', f"## {ui['new']}", ""]
    if not items:
        return out + [ui["new_none"], ""]
    out += [ui["new_count"].format(days=NEW_DAYS, n=len(items)), ""]
    for s in items:
        n = meta.get(s["repo"], {}).get("stars")
        star = f" ★{fmt_stars(n)}" if n is not None else ""
        out.append(ui["new_item"].format(name=display_name(s), url=gh_url(s["repo"]), star=star,
                                         desc=cell(tr(s, "desc", lang))))
    return out + [""]


def links(items) -> str:
    return " · ".join(f"[{display_name(s)}]({gh_url(s['repo'])})" for s in items)


def render_index(field: str, f: dict, skills: list[dict], meta: dict, ui: dict, lang: str) -> list[str]:
    """一个维度的索引。split_max 设了，就把每项拆成「专项」（维度值不超过 split_max 个）和「综合」两行。"""
    out = [f'<a id="by-{field}"></a>', f"## {tr(f, 'title', lang)}", ""]
    if f.get("intro"):
        out += [tr(f, "intro", lang), ""]
    split = f.get("split_max")
    for key in ordered(f, lang):
        v = f["values"][key]
        hits = by_stars((s for s in skills if key in s.get(field, [])), meta)
        if not hits:
            continue
        label = value_label(v, lang)
        if not split:
            out += [ui["index_item"].format(label=label, n=len(hits), links=links(hits)), ""]
            continue
        focused = [s for s in hits if len(s[field]) <= split]
        broad = [s for s in hits if len(s[field]) > split]
        out += [ui["index_head"].format(label=label, n=len(hits)), ""]
        out += [ui["index_line"].format(name=ui[name], n=len(items), links=links(items))
                for name, items in (("focused", focused), ("broad", broad)) if items]
        out += [""]
    return out


def fill(text: str, taxonomy: dict, skills: list[dict], indexed: list[dict], ignored: list[dict],
         meta_all: dict, ui: dict) -> str:
    """把模板里的 {{占位符}} 换成从数据算出的数。"""
    meta = meta_all.get("repos", {})

    def top(items):
        names = [f"[{display_name(s)}]({gh_url(s['repo'])})" for s in by_stars(items, meta)[:3]]
        sep, last = ui["join"]
        return sep.join(names[:-1]) + last + names[-1] if len(names) > 1 else "".join(names) or "—"

    def pick(kind: str, args: list[str]) -> list[dict]:
        if kind == "group":
            return [s for s in skills if s["group"] == args[0]]
        if kind == "facet":
            pool = skills if facets(taxonomy)[args[0]].get("include_all") else indexed
            return [s for s in pool if args[1] in s.get(args[0], [])]
        if kind == "format":
            return [s for s in indexed if s["format"] == args[0]]
        if kind == "agent":
            return [s for s in indexed if args[0] in s.get("agents", [])]
        raise KeyError(kind)

    simple = {"count": len(indexed), "platforms": len(skills) - len(indexed), "updated": meta_all.get("fetched_at") or "—",
              "total": len(skills) + len(ignored), "ignored": len(ignored)}

    def sub(m: re.Match) -> str:
        parts = m.group(1).split(":")
        if len(parts) == 1:
            return str(simple[parts[0]])
        if parts[0] == "top":
            return top(pick(parts[1], parts[2:]))
        return str(len(pick(parts[0], parts[1:])))

    return re.sub(r"\{\{([a-z_]+(?::[A-Za-z0-9_.-]+)*)\}\}", sub, text)


def template(name: str, lang: str) -> str | None:
    path = TEMPLATES / (f"{name}.md" if lang == "zh" else f"{name}.{lang}.md")
    return path.read_text(encoding="utf-8").rstrip() if path.exists() else None


def render(taxonomy: dict, skills: list[dict], ignored: list[dict], meta_all: dict, lang: str) -> str:
    ui = UI[lang]
    meta = meta_all.get("repos", {})
    ref = dt.date.fromisoformat(meta_all["fetched_at"]) if meta_all.get("fetched_at") else None
    groups = taxonomy["groups"]
    grouped = {k: sorted((s for s in skills if s["group"] == k), key=lambda s: sort_key(s, meta)) for k in groups}
    indexed = [s for s in skills if groups[s["group"]].get("indexed", True)]
    indexes = {field: f for field, f in facets(taxonomy).items() if f.get("index")}
    filled = lambda text: fill(text, taxonomy, skills, indexed, ignored, meta_all, ui)  # noqa: E731

    new = new_entries(skills, meta, ref)
    count = ui["count"].format
    faq = template("faq", lang)
    toc = [f"## {ui['toc']}", "", f"- [{ui['new']}](#new){count(len(new))}", f"- [{ui['by_group']}](#by-group)"]
    toc += [f"  - [{tr(g, 'label', lang)}](#group-{k}){count(len(grouped[k]))}" for k, g in groups.items() if grouped[k]]
    toc += [f"- [{tr(f, 'title', lang)}](#by-{field})" for field, f in indexes.items()]
    if faq:
        toc.append(f"- [{ui['faq']}](#faq)")
    toc += [f"- [{ui['resources']}](#resources)", f"- [{ui['badge']}](#badge)", ""]

    body = ['<a id="by-group"></a>', f"## {ui['by_group']}", ""]
    for k, g in groups.items():
        if grouped[k]:
            body += render_group(k, g, grouped[k], meta, ref, taxonomy, ui, lang)
    for field, f in indexes.items():
        body += render_index(field, f, skills if f.get("include_all") else indexed, meta, ui, lang)
    if faq:
        body += ['<a id="faq"></a>', f"## {ui['faq']}", "", filled(faq), ""]

    parts = [ui["generated"], "", filled(template("header", lang) or ""), "", *toc, *render_new(new, meta, ui, lang),
             *body, filled(template("footer", lang) or ""), ""]
    return "\n".join(parts)


def catalog(taxonomy: dict, skills: list[dict], meta_all: dict) -> str:
    """给 agent 读的目录：五个清单格式一样，推荐官 skill 和以后的汇总都读它。"""
    meta = meta_all.get("repos", {})
    groups = taxonomy["groups"]
    fs = facets(taxonomy)
    two = lambda obj, key="label": {key: tr(obj, key, "zh"), f"{key}_en": tr(obj, key, "en")}  # noqa: E731
    entries = []
    for k in groups:
        for s in sorted((s for s in skills if s["group"] == k), key=lambda s: sort_key(s, meta)):
            m = meta.get(s["repo"], {})
            e = {"repo": s["repo"], "url": gh_url(s["repo"]), "name": display_name(s), "group": s["group"]}
            e.update({field: s.get(field, []) for field in fs})
            e.update(format=s["format"], lang=s["lang"], agents=s.get("agents", []), featured=s.get("tier") == "featured",
                     desc=s["desc"], desc_en=s.get("desc_en", ""), note=s.get("note", ""), note_en=s.get("note_en", ""),
                     stars=m.get("stars"), pushed_at=m.get("pushed_at"), license=m.get("license"),
                     skills=m.get("skill_count"), install=install_cmd(s), checked=s["checked"].isoformat())
            entries.append(e)
    out = {
        "name": ROOT.name,
        "url": gh_url(taxonomy.get("list", {}).get("repo", ROOT.name)),
        "updated": meta_all.get("fetched_at"),
        "format_version": 1,
        "groups": {k: {**two(g), "indexed": g.get("indexed", True)} for k, g in groups.items()},
        "facets": {field: {**two(f, "title"), "values": {k: {"label": value_label(v, "zh"), "label_en": value_label(v, "en")}
                                                         for k, v in f["values"].items()}} for field, f in fs.items()},
        "formats": {k: (v if isinstance(v, str) else v.get("label")) for k, v in taxonomy["formats"].items()},
        "entries": entries,
    }
    return json.dumps(out, ensure_ascii=False, indent=1) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="只检查生成结果是否最新")
    ap.add_argument("--validate", action="store_true", help="只校验数据")
    args = ap.parse_args()

    taxonomy, skills, ignored = load_valid()
    if args.validate:
        print(f"数据校验通过：{len(skills)} 个项目，{len(ignored)} 个不收。")
        return

    meta_all = load_meta()
    unfetched = [s["repo"] for s in skills if s["repo"] not in meta_all.get("repos", {})]
    if unfetched:
        print(f"提示：{len(unfetched)} 个仓库还没有元数据，先运行 scripts/refresh.py --only {' '.join(unfetched)}",
              file=sys.stderr)

    outputs = {path: render(taxonomy, skills, ignored, meta_all, lang) for lang, path in OUTPUTS.items()}
    outputs[CATALOG] = catalog(taxonomy, skills, meta_all)
    if args.check:
        stale = [p.name for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            sys.exit(f"{'、'.join(stale)} 不是最新的，请运行 python3 scripts/build.py")
        print("README 和 catalog.json 已是最新。")
        return
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
    print(f"已生成 {'、'.join(p.name for p in outputs)}：{len(skills)} 个项目。")


if __name__ == "__main__":
    main()
