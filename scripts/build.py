"""根据 data/ 和 templates/ 生成 README.md、README.en.md 和 catalog.json（给 agent 读的目录）。

本文件来自共用代码 kit（见 scripts/KIT），各清单内容一样。
清单自己的东西：分类、维度和搜索词在 data/taxonomy.toml，条目在 data/skills.toml，
开头、结尾和常见问题在 templates/header*.md、footer*.md、faq*.md。

常见问题和开头里可以写这些占位符，生成时换成从数据算出的数：
  {{count}} 收录的 skill 项目数   {{platforms}} 不算 skill 的项目数（应用、MCP 等）   {{updated}} 元数据日期
  {{total}} 审过的仓库数          {{ignored}} 没收的仓库数
  {{group:键}} 某个分组的项目数   {{facet:字段:值}} 带某个维度值的项目数   {{format:键}} {{agent:键}}
  {{top:group:键}} {{top:facet:字段:值}} 星数前三的项目链接
维度默认只算 skill（不算 indexed = false 分组里的应用和工具）；维度设了 include_all = true 就全算。

用法：
  python3 scripts/build.py              # 生成
  python3 scripts/build.py --check      # 生成结果和仓库里的不一致时以退出码 1 结束（CI 用）
  python3 scripts/build.py --validate   # 只校验数据
"""

